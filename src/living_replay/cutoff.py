"""M8 — the model-layer early cutoff, measured (P7 refinement).

The doctrine (2026-10-16): after an edit, work resumes "from the first
model call whose context bytes actually changed" — a model call whose
context is byte-identical after recompute replays from the record
instead of being re-asked. Until this module, that rule was an
unmeasured proposal: the deterministic engine had its cutoff gate
(B2-G6/B2-G6b), but nobody had counted, on recorded material, how much
work a context-bytes check would actually save, or where the cutoff
lands. This module is the measurement harness. It makes no behavior
change; it counts.

Two layers, matching the two halves of the question:

NODE LAYER — `node_cutoff(engine, target, value)`. For one edit on a
built incremental Engine, force-recompute EVERY invalidated node (the
transitive dependents of the edited input, in topological order) and
compare each recomputed output to the recorded output as canonical
bytes (`store.canonical`). Reports: the invalidated count, how many
recomputes are byte-identical, which nodes truly changed, the cutoff
position (the 1-based position in the invalidated order of the LAST
changed node — after it, every remaining recompute is provably wasted
work), the tail that could stop there, and how many nodes the shipped
Engine actually executes under its own value-cutoff rule, for
comparison. Byte identity, not ==, is the standard throughout: it is
the same serialization the store hash-chains.

SESSION LAYER — `session_cutoff(events, rewrite)`. For a recorded
branch (the event list from `store.replay_events`), a model call's
context is the canonical bytes of its recorded context prefix — the
`runner.context_at` stream (tool_call / model_call / context_note
payloads) strictly before the call — plus the call's own prompt. A
counterfactual is a `rewrite` function mapping the recorded event list
to a corrected one. Each call's context bytes are recomputed on the
rewritten stream and compared: calls before the first difference could
replay their recorded outputs verbatim; the first differing call is
the cutoff, the point where re-asking must resume. The rule is
deliberately conservative (any prefix byte change forces a re-ask,
even a semantically irrelevant one) and sound only where the recorded
context is the whole context — true by construction for sessions
recorded through the runner, where `context_at` is literally what a
fork re-primes with. Where a computation has inputs that never appear
in any event payload, the count is an upper bound, not a promise; the
results doc says which corpora carry that caveat.

Corpora measured (`measure_all`): the flagship fixture graph and the
flagship recorded store (generated by `flagship.run_flagship`), the
Build 2 gate corpus graph (93 nodes, construction mirrored from
tests/test_build2.py's IncrementalGate), and a scripted multi-call
session recorded into a real TimelineStore through the same append
path the runner uses. The Build 2 live-session store (153 events,
16 model calls) does not exist in this repo — it lives on the sandbox
host — so every number here is a fixture/harness measurement and is
labeled as such in docs/m8-early-cutoff.md.

Run it:  python -m living_replay.cutoff [--out results.json]
"""
from __future__ import annotations
import argparse, copy, json, statistics, sys, tempfile
from pathlib import Path
from typing import Any, Callable

from .incremental import Engine
from .runner import CONTEXT_KINDS
from .store import TimelineStore, canonical

Rewrite = Callable[[list[dict]], list[dict]]


# ---------------------------------------------------------------- node layer

def node_cutoff(engine: Engine, target: str, value: Any) -> dict:
    """Force-recompute measurement of one edit on a built Engine.

    The engine is NOT mutated: the walk runs on a copy of its cache,
    with node functions invoked exactly as Engine.build invokes them.
    Alongside the forced walk, the shipped Engine's own rule (execute
    a candidate only when a dependency's value changed) is simulated
    on the same changed-set, so the report shows both what the engine
    does today and what byte-identity says was necessary.
    """
    if target not in engine.inputs:
        raise ValueError(f"{target!r} is not an input of this engine")
    recorded = {n: canonical(v) for n, v in engine.cache.items()}
    invalidated: set[str] = set()
    stack = list(engine.dependents.get(target, ()))
    while stack:
        cur = stack.pop()
        if cur in invalidated:
            continue
        invalidated.add(cur)
        stack.extend(engine.dependents.get(cur, ()))
    index = engine._index()
    order = sorted(invalidated, key=index.__getitem__)

    working = dict(engine.cache)
    changed: set[str] = set()
    if canonical(value) != recorded[target]:
        changed.add(target)
        working[target] = value
    identical: list[str] = []
    changed_nodes: list[str] = []
    executed: list[str] = []
    cutoff_position = 0
    for pos, node in enumerate(order, start=1):
        if engine.deps[node] & changed:
            executed.append(node)  # the shipped Engine would run this one
        new = engine.fns[node](working)
        working[node] = new
        if canonical(new) == recorded[node]:
            identical.append(node)
        else:
            changed.add(node)
            changed_nodes.append(node)
            cutoff_position = pos
    n = len(order)
    return {
        "target": target, "value": value,
        "graph_nodes": len(engine.fns),
        "invalidated": order, "invalidated_n": n,
        "byte_identical": identical, "byte_identical_n": len(identical),
        "byte_identical_fraction": (len(identical) / n) if n else 0.0,
        "changed": changed_nodes, "changed_n": len(changed_nodes),
        "cutoff_position": cutoff_position,
        "tail_stoppable_n": n - cutoff_position,
        "tail_fraction": ((n - cutoff_position) / n) if n else 0.0,
        "engine_executed": executed, "engine_executed_n": len(executed),
        "final_values": working,
    }


def _aggregate(rows: list[dict], keys: list[str]) -> dict:
    out: dict[str, Any] = {"n": len(rows)}
    for k in keys:
        vals = [r[k] for r in rows]
        if vals:
            out[k] = {"mean": statistics.fmean(vals),
                      "median": statistics.median(vals),
                      "min": min(vals), "max": max(vals)}
    return out


