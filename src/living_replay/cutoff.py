def flagship_engine() -> Engine:
    """The flagship fixture's computation as an incremental Engine,
    built and evaluated at the recorded intake values."""
    from . import flagship
    g = flagship.build_fact_graph(flagship.INTAKE)
    inputs = {p: f.value for p, f in g.facts.items() if f.formula is None}
    e = flagship._engine_from_graph(g, inputs)
    e.build()
    return e


FLAGSHIP_EDITS: list[tuple[str, Any]] = [
    # Wages/withholding values are floats: the lens extracts them as
    # floats, and canonical bytes are type-sensitive (52000 and
    # 52000.0 are different bytes) — the no-op row below depends on
    # using the recorded type, and the sensitivity itself is one of
    # the measurement's findings (see docs/m8-early-cutoff.md).
    ("/wages", 48000.0), ("/wages", 50000.0), ("/wages", 51900.0),
    ("/wages", 52100.0), ("/wages", 76000.0), ("/wages", 52000.0),
    ("/withholding", 6000.0), ("/withholding", 6200.0),
    ("/otherIncome", 500), ("/standardDeduction", 15000),
    ("/stateWages", 48000), ("/stateWithholding", 950),
    ("/dependents", 2), ("/dependents", 0),
]


def corpus_engine() -> Engine:
    """The Build 2 gate corpus graph (93 derived nodes): two 40-node
    record chains, a threshold flag, an 11-node gated chain, and a
    join. Construction mirrors tests/test_build2.py IncrementalGate
    so the M8 numbers are directly comparable to B2-G6/B2-G6b."""
    def bump(t, by=1):
        return tuple(x + by for x in t)
    e = Engine()
    e.add_input("A", tuple(range(32))).add_input("B", tuple(range(100, 132)))
    prev = "A"
    for i in range(1, 41):
        name = f"a{i}"
        e.add(name, lambda v, p=prev: bump(v[p]), [prev])
        prev = name
    e.add("flag", lambda v: v["a40"][0] > 1_000_000, ["a40"])
    e.add("s0", lambda v: (100,) * 32 if v["flag"] else (1,) * 32, ["flag"])
    prev = "s0"
    for i in range(1, 11):
        name = f"s{i}"
        e.add(name, lambda v, p=prev: bump(v[p], 100 if v["flag"] else 1),
              [prev, "flag"])
        prev = name
    prev = "B"
    for i in range(1, 41):
        name = f"b{i}"
        e.add(name, lambda v, p=prev: bump(v[p]), [prev])
        prev = name
    e.add("join", lambda v: tuple(a + b + s for a, b, s in
                                  zip(v["a40"], v["b40"], v["s10"])),
          ["a40", "b40", "s10"])
    e.build()
    return e


CORPUS_EDITS: list[tuple[str, Any]] = [
    ("A", tuple(x + 999 for x in range(32))),        # the B2-G6 gate edit
    ("A", tuple(x + 1_000_001 for x in range(32))),  # flag-crossing edit
    ("B", tuple(x + 7 for x in range(100, 132))),    # untouched by A edits
    ("A", tuple(range(32))),                          # no-op edit
]


def record_scripted_session(root: str | Path) -> TimelineStore:
    """A three-model-call session recorded into a real TimelineStore
    through the store append path the runner's ForkContext uses:
    read an amount, double it (model), print, read a rate, apply it
    (model), print, summarize (model). Scripted, and labeled as such:
    it exists because no multi-call recorded session ships in this
    repo, and the session-layer measurement needs more than the
    flagship's single call to show where a cutoff lands."""
    store = TimelineStore(Path(root) / "timeline")
    store.append("main", "tool_call",
                 {"name": "read-amount", "input": "data.txt",
                  "output": "amount=21", "amount": 21})
    store.append("main", "model_call",
                 {"prompt": "double the amount", "tokens": "42",
                  "replayed": True})
    store.append("main", "tool_call",
                 {"name": "print-total", "input": "print",
                  "output": "total=42"})
    store.append("main", "tool_call",
                 {"name": "read-rate", "input": "data.txt",
                  "output": "rate=2", "rate": 2})
    store.append("main", "model_call",
                 {"prompt": "apply the rate to the total", "tokens": "84",
                  "replayed": True})
    store.append("main", "tool_call",
                 {"name": "print-final", "input": "print",
                  "output": "final=84"})
    store.append("main", "model_call",
                 {"prompt": "summarize the session",
                  "tokens": "amount 21 doubled to 42; rate 2 applied for 84",
                  "replayed": True})
    return store


# ---------------------------------------------------------------- session layer

def call_contexts(events: list[dict]) -> list[bytes]:
    """Canonical context bytes per model call, in branch order: the
    recorded context prefix (CONTEXT_KINDS payloads) before the call,
    plus the call's own prompt. The call's recorded output is NOT part
    of its own context; earlier calls' outputs are part of later
    calls' contexts, exactly as `runner.context_at` re-primes them."""
    contexts: list[bytes] = []
    prefix: list[dict] = []
    for ev in events:
        if ev["kind"] not in CONTEXT_KINDS:
            continue
        if ev["kind"] == "model_call":
            ctx = [{"kind": p["kind"], "payload": p["payload"]}
                   for p in prefix]
            ctx.append({"kind": "model_call",
                        "prompt": (ev["payload"] or {}).get("prompt")})
            contexts.append(canonical(ctx))
        prefix.append(ev)
    return contexts


def session_cutoff(events: list[dict], rewrite: Rewrite) -> dict:
    """Measure where the context-bytes cutoff lands under a
    counterfactual rewrite of the recorded event list.

    `replayable` counts calls strictly before the first differing
    context: once one call must be re-asked, its new output can differ
    from the record, so every later context is unverifiable against
    the record even if its static bytes happen to match again
    (`identical_total` reports that looser count as an upper bound).
    """
    before = call_contexts(events)
    after = call_contexts(rewrite(copy.deepcopy(events)))
    n = len(before)
    flags = [(i < len(after) and after[i] == b)
             for i, b in enumerate(before)]
    cutoff = next((i for i, ok in enumerate(flags) if not ok), None)
    replayable = cutoff if cutoff is not None else n
    return {
        "model_calls": n, "model_calls_after": len(after),
        "identical": flags, "identical_total": sum(flags),
        "cutoff_index": cutoff,
        "replayable": replayable,
        "replayable_fraction": (replayable / n) if n else 0.0,
    }


def _replace_payload_field(name: str, field: str, value: Any) -> Rewrite:
    """Rewrite builder: set one payload field on the named tool call."""
    def rw(events: list[dict]) -> list[dict]:
        for ev in events:
            if ev["kind"] == "tool_call" and \
                    (ev["payload"] or {}).get("name") == name:
                ev["payload"][field] = value
        return events
    return rw


def _intake_rewrite(put: Callable[[str, float], str], value: float) -> Rewrite:
    """Rewrite builder: amend the flagship intake document wherever it
    appears as a recorded payload string (the lens-amended document is
    exactly what the ghost branch recomputes from)."""
    from . import flagship
    def rw(events: list[dict]) -> list[dict]:
        for ev in events:
            payload = ev["payload"] or {}
            for k, v in payload.items():
                if isinstance(v, str) and v == flagship.INTAKE:
                    payload[k] = put(v, value)
        return events
    return rw


def scripted_scenarios(store: TimelineStore) -> list[dict]:
    events = store.replay_events("main")
    scenarios = [
        ("identity (sanity)", lambda evs: evs),
        ("correct the amount (first event)",
         _replace_payload_field("read-amount", "amount", 25)),
        ("correct the rate (mid-session)",
         _replace_payload_field("read-rate", "rate", 3)),
        ("correct the final print (after two calls)",
         _replace_payload_field("print-final", "output", "final=84 (rev)")),
    ]
    return [{"scenario": name, **session_cutoff(events, rw)}
            for name, rw in scenarios]


def flagship_store_scenarios(store: TimelineStore) -> list[dict]:
    from . import flagship
    events = store.replay_events("main")
    scenarios = [
        ("identity (sanity)", lambda evs: evs),
        ("correct wages in the intake (lens)",
         _intake_rewrite(flagship.WagesLens.put, 48000)),
        ("correct withholding in the intake (lens)",
         _intake_rewrite(flagship.WithholdingLens.put, 6000)),
        ("correct the printout (after the call)",
         _replace_payload_field("print-return", "output",
                                 "totalTax=3568 refund=2532 (reprint)")),
    ]
    return [{"scenario": name, **session_cutoff(events, rw)}
            for name, rw in scenarios]


# ---------------------------------------------------------------- inventory + all

def store_inventory(registry: Path) -> list[dict]:
    """Every store registered in service/stores.json: what it holds
    and whether the session-layer measurement can run on it."""
    from collections import Counter
    reg = json.loads(registry.read_text())
    rows = []
    for name, cfg in reg["stores"].items():
        row: dict[str, Any] = {"store": name, "label": cfg.get("label")}
        if cfg.get("generate"):
            row["suitable"] = ("yes — generated flagship fixture; measured "
                               "via flagship.run_flagship")
            row["note"] = "not materialized on disk until generated"
            rows.append(row)
            continue
        path = Path(cfg["path"]).expanduser()
        if not path.exists():
            row["suitable"] = "unknown — path not present on this machine"
            rows.append(row)
            continue
        store = TimelineStore(path)
        branches = [r[0] for r in store.db.execute(
            "select distinct branch from events order by branch")]
        kinds: Counter = Counter()
        models = 0
        for b in branches:
            evs = store.events(b)
            kinds.update(e["kind"] for e in evs)
            models += sum(1 for e in evs if e["kind"] == "model_call")
        row["branches"] = branches
        row["event_kinds"] = dict(kinds)
        row["model_calls"] = models
        row["suitable"] = ("yes" if models else
                            "no — no recorded model calls in this store")
        rows.append(row)
    return rows


def _public(row: dict) -> dict:
    return {k: v for k, v in row.items() if k != "final_values"}


def measure_all(workdir: str | Path) -> dict:
    """Run every measurement and return one JSON-able report."""
    from . import flagship
    workdir = Path(workdir)
    workdir.mkdir(parents=True, exist_ok=True)

    fe = flagship_engine()
    flagship_rows = [_public(node_cutoff(fe, t, v)) for t, v in FLAGSHIP_EDITS]
    ce = corpus_engine()
    corpus_rows = [_public(node_cutoff(ce, t, v)) for t, v in CORPUS_EDITS]

    result = flagship.run_flagship(workdir / "flagship")
    scripted = record_scripted_session(workdir / "scripted")

    registry = Path(__file__).resolve().parent.parent.parent / \
        "service" / "stores.json"
    return {
        "corpora_labeled": "fixture/harness measurements — the Build 2 "
                           "live-session store is not in this repo",
        "stores": store_inventory(registry),
        "node_layer": {
            "flagship": {
                "edits": flagship_rows,
                "aggregate": _aggregate(
                    flagship_rows,
                    ["byte_identical_fraction", "tail_fraction",
                     "invalidated_n", "engine_executed_n"]),
            },
            "corpus93": {
                "edits": corpus_rows,
                "aggregate": _aggregate(
                    corpus_rows,
                    ["byte_identical_fraction", "tail_fraction",
                     "invalidated_n", "engine_executed_n"]),
            },
        },
        "session_layer": {
            "flagship_store": flagship_store_scenarios(result["store"]),
            "scripted_session": scripted_scenarios(scripted),
        },
    }


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(
        description="M8 early-cutoff measurement (see module docstring)")
    ap.add_argument("--out", help="write the JSON report here "
                                  "(default: stdout)")
    args = ap.parse_args(argv)
    with tempfile.TemporaryDirectory() as td:
        report = measure_all(Path(td))
    text = json.dumps(report, indent=2, default=str)
    if args.out:
        Path(args.out).write_text(text + "\n")
    else:
        print(text)
    return 0


if __name__ == "__main__":
    sys.exit(main())
