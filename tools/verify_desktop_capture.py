"""Forward-verify M9 against an isolated real Chromium browser.

Run with --browser /path/to/chromium (or msedge.exe). All application
content is synthetic. The recorder only reads AX trees; this harness
separately drives the test page using labeled synthetic mouse input.
Requires the desktop extra. Nothing is written to a user's browser profile.
"""
from __future__ import annotations

import argparse
import json
import os
from pathlib import Path
import subprocess
import tempfile
import time

from living_replay import ingest
from living_replay.desktop import CDPClient, capture_desktop, select_target
from living_replay.store import TimelineStore


PAGE = """<!doctype html><meta charset="utf-8"><title>Melange synthetic M9</title>
<button autofocus aria-expanded="false" onclick="
const open=this.getAttribute('aria-expanded')==='false';
this.setAttribute('aria-expanded', String(open));
document.getElementById('details').hidden=!open;
">Toggle synthetic details</button>
<section id="details" hidden><h1>Synthetic details</h1><p>Total: 42</p></section>
"""


def verify(browser):
    with tempfile.TemporaryDirectory(prefix="melange-m9-", ignore_cleanup_errors=True) as tmp:
        root = Path(tmp)
        page = root / "synthetic.html"
        page.write_text(PAGE, encoding="utf-8")
        profile = root / "profile"
        proc = subprocess.Popen([
            browser, "--headless=new", "--disable-gpu", "--no-first-run",
            "--no-default-browser-check", "--remote-debugging-port=0",
            f"--user-data-dir={profile}", page.as_uri(),
        ], stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL,
            creationflags=subprocess.CREATE_NO_WINDOW if os.name == "nt" else 0)
        client = None
        try:
            port_file = profile / "DevToolsActivePort"
            deadline = time.monotonic() + 20
            while not port_file.exists():
                if proc.poll() is not None or time.monotonic() > deadline:
                    raise RuntimeError("test browser did not expose its CDP endpoint")
                time.sleep(.1)
            port = int(port_file.read_text().splitlines()[0])
            # The endpoint belongs to a fresh profile launched above. Discover
            # the exact synthetic page id without choosing any personal tab.
            from urllib.request import urlopen
            endpoint = f"http://127.0.0.1:{port}"
            target = None
            while target is None:
                with urlopen(endpoint + "/json/list", timeout=5) as response:
                    targets = json.load(response)
                target = next((t for t in targets if t.get("url") == page.as_uri()), None)
                if target is None:
                    if time.monotonic() > deadline:
                        raise RuntimeError("synthetic test page did not open")
                    time.sleep(.1)
            selected = select_target(endpoint, target["id"])
            client = CDPClient(selected)
            client.call("Page.enable")
            while client.call("Runtime.evaluate", {"expression": "document.readyState"})["result"].get("value") != "complete":
                if time.monotonic() > deadline:
                    raise RuntimeError("synthetic page did not finish loading")
                time.sleep(.05)
            expected = []

            class Observer:
                def call(self, method, params=None):
                    if method == "Accessibility.getFullAXTree":
                        if len(expected) in (1, 3):
                            # Inputs are generated by the test harness, never
                            # attributed to a user or captured as causal data.
                            point = client.call("Runtime.evaluate", {
                                "expression": "(() => { const r=document.querySelector('button').getBoundingClientRect(); return {x:r.x+r.width/2,y:r.y+r.height/2}; })()",
                                "returnByValue": True,
                            })["result"]["value"]
                            for typ in ("mousePressed", "mouseReleased"):
                                client.call("Input.dispatchMouseEvent", {
                                    "type": typ, **point, "button": "left", "clickCount": 1,
                                })
                            time.sleep(.1)
                        result = client.call(method, params)
                        expected.append(ingest.flatten_ax(result["nodes"]))
                        return result
                    return client.call(method, params)

            output = root / "capture.jsonl"
            capture_desktop(Observer(), output, samples=4, interval=.15)
            record = output.read_text(encoding="utf-8")
            store = TimelineStore(root / "timeline")
            try:
                counts = ingest.ingest_desktop_record(store, "desktop", record)
                frames = [e for e in store.events("desktop")
                          if e["kind"] in {"ax_keyframe", "ax_delta"}]
                assert len(frames) == len(expected) == 4
                for ev, state in zip(frames, expected):
                    assert ingest.tree_state_at(store, "desktop", ev["id"]) == state
                assert expected[0] != expected[1], "mouse input did not change the real AX tree"
                assert expected[1] == expected[2], "still-window poll changed unexpectedly"
                assert expected[2] != expected[3], "second mouse input did not change the tree"
                assert store.verify("desktop")
                for op in ("clamp", "fork", "provenance"):
                    try:
                        ingest.require_branch_op(store, "desktop", op)
                    except ingest.FidelityError:
                        pass
                    else:
                        raise AssertionError(f"structure record incorrectly permits {op}")
                return {"frames_verified": len(frames), "differing_paths": 0,
                        "keyframes": counts["keyframes"], "delta_ops": counts["delta_ops"],
                        "still_poll_ops": len(json.loads(record.splitlines()[2])["ops"]),
                        "fidelity": "structure", "synthetic_test_inputs": 2,
                        "refused": ["clamp", "fork", "provenance"], "seal": True}
            finally:
                store.db.close()
        finally:
            if client is not None:
                try:
                    client.call("Browser.close")
                except Exception:
                    pass
                client.close()
            try:
                proc.wait(timeout=5)
            except subprocess.TimeoutExpired:
                proc.terminate()
                proc.wait(timeout=5)


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--browser", required=True)
    args = parser.parse_args()
    print(json.dumps(verify(args.browser), indent=2))
